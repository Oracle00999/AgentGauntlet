import { test,expect } from '@playwright/test';
import { mkdir,writeFile } from 'node:fs/promises';
process.loadEnvFile('.env');
test('browser login, real saved reports, security boundary and responsive layout',async({page,request})=>{
  const forbidden=await request.get('/api/proxy/test-runs');expect(forbidden.status()).toBe(401);
  const crossSite=await request.post('/api/session',{headers:{origin:'https://untrusted.example'},data:{code:'irrelevant'}});expect(crossSite.status()).toBe(403);
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('Workspace access code').fill(process.env.WEB_ACCESS_CODE!);
  await page.getByRole('button',{name:'Open workspace'}).click();
  await expect(page.getByRole('heading',{name:'Break the agent. Protect the wallet.'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Run scenario'})).toBeEnabled();
  await expect(page.locator('.metric').first().locator('strong')).not.toHaveText('—');
  if(await page.getByLabel('Agent',{exact:true}).locator('option[value="external-demo"]').count())await page.getByLabel('Agent',{exact:true}).selectOption('external-demo');
  await page.getByLabel('Payment system',{exact:true}).selectOption('near-permissive');
  await page.getByLabel('Execution mode',{exact:true}).selectOption('probe');
  await expect(page.getByLabel('Agent',{exact:true})).toBeDisabled();
  await expect(page.getByText('No model decision is generated.',{exact:false})).toBeVisible();
  await page.getByLabel('Execution mode',{exact:true}).selectOption('agent');
  await page.getByLabel('Agent',{exact:true}).selectOption('shoppingbot');
  await page.getByLabel('Payment system',{exact:true}).selectOption('near-protected');
  const html=await page.content();expect(html).not.toContain(process.env.API_TOKEN!);expect(html).not.toContain(process.env.OPENAI_API_KEY!);
  const session=(await page.context().cookies()).find(c=>c.name==='ag_session');expect(session?.httpOnly).toBe(true);expect(session?.sameSite).toBe('Strict');
  await mkdir('artifacts/ui',{recursive:true});
  await page.screenshot({path:'artifacts/ui/attack-lab-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Controls',exact:true}).click();expect(await page.locator('.scenario-card').count()).toBe(1);
  await page.getByRole('button',{name:'All scenarios'}).click();
  await expect(page.locator('.scenario-card')).toHaveCount(7);
  await page.getByRole('button',{name:/Split-payment budget evasion/}).click();
  await expect(page.getByLabel('Payment system',{exact:true})).toHaveValue('near-budget');
  await page.getByRole('button',{name:/Malicious invoice/}).click();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'artifacts/ui/attack-lab-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Open navigation'}).click();await page.getByRole('link',{name:'Test runs',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Test runs',exact:true})).toBeVisible();
  const row=page.locator('tbody tr').filter({has:page.locator('.badge.green')}).first();await expect(row).toBeVisible();await row.locator('.run-link').click();
  await expect(page.getByRole('heading',{name:'Execution timeline'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Export JSON'})).toBeEnabled({timeout:20000});
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'artifacts/ui/security-report-desktop.png',fullPage:true});
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export JSON'}).click();expect((await download).suggestedFilename()).toMatch(/^agentgauntlet-.*\.json$/);
  await page.locator('.timeline-event').first().locator('summary').click();await expect(page.locator('.timeline-event').first().locator('pre')).toBeVisible();
  const badOrigin=await page.request.post('/api/proxy/test-runs',{headers:{origin:'https://untrusted.example'},data:{scenarioId:'malicious-invoice'}});expect(badOrigin.status()).toBe(403);
  await page.goto('/compare');
  await expect(page.getByRole('heading',{name:'Compare runs',exact:true})).toBeVisible();
  await expect(page.locator('.comparison-report')).toHaveCount(2);
  await expect(page.getByText('Same deterministic payment requests and authorized task.',{exact:false})).toBeVisible();
  await page.screenshot({path:'artifacts/ui/comparison-desktop.png'});
  const probeReport=page.locator('.comparison-report').first().getByRole('link',{name:'Open security report'});
  await probeReport.click();
  await expect(page.locator('.model-label')).toHaveText('Scripted probe · model not invoked');
  await page.goto('/compare');
  await expect(page.locator('.comparison-report')).toHaveCount(2);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'artifacts/ui/comparison-mobile.png'});
  expect(errors).toEqual([]);
});
test('launch a real malicious-invoice test from the browser',async({page})=>{
  test.skip(process.env.WEB_LIVE_TEST!=='1','Opt-in: uses actual OpenAI calls and testnet funds');test.setTimeout(600000);
  await page.goto('/login');await page.getByLabel('Workspace access code').fill(process.env.WEB_ACCESS_CODE!);await page.getByRole('button',{name:'Open workspace'}).click();
  await page.getByRole('button',{name:'Run scenario'}).click();await expect(page).toHaveURL(/\/runs\/[0-9a-f-]{36}$/);
  const runId=new URL(page.url()).pathname.split('/').pop();console.log('UI-launched run:',runId);
  await expect(page.getByRole('heading',{name:'Execution timeline'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Export JSON'})).toBeEnabled({timeout:540000});
  const response=await page.request.get(`/api/proxy/test-runs/${runId}/report`);const report=await response.json();
  expect(report.completed).toBe(true);expect(report.outcome).not.toBe('INCONCLUSIVE');
  await writeFile('artifacts/ui/live-browser-report.json',JSON.stringify(report,null,2));
  await page.screenshot({path:'artifacts/ui/live-browser-report.png',fullPage:true});
  console.log('UI outcome:',report.outcome);
});
